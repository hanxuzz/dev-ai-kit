# Idempotent workspace install. Does not overwrite project.yaml, project.local.yaml, or an existing rule.
param(
  [Parameter(Mandatory = $true)][string]$Workspace,
  [string]$Kit = '',
  [string]$DocsMode = '',
  [string]$DocsRepo = '',
  [string]$SharePath = ''
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'lib.ps1')

function Fail([string]$Code, [string]$Detail) {
  Write-Output "FAIL $Code $Detail"
  exit 1
}

if (-not (Test-Path -LiteralPath $Workspace)) { Fail 'no-workspace' $Workspace }
$Workspace = (Resolve-Path -LiteralPath $Workspace).Path

if (-not $Kit) { $Kit = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path }
if (-not (Test-Path -LiteralPath (Join-Path $Kit 'AGENTS.md'))) { Fail 'kit-missing' $Kit }
$Kit = (Resolve-Path -LiteralPath $Kit).Path

if (Test-Path -LiteralPath (Join-Path $Workspace '.git')) {
  Fail 'workspace-is-code-repo' 'Open the parent folder that contains the code repositories, not a single repository.'
}

$skip = @('.cursor', '.git', 'node_modules', 'dist', 'target')
$repos = @()
Get-ChildItem -LiteralPath $Workspace -Directory | ForEach-Object {
  if ($skip -contains $_.Name) { return }
  if (Test-CodeRoot $_.FullName) { $repos += $_.Name }
}
if ($repos.Count -eq 0) {
  Fail 'no-code-roots' 'No child directory with a project marker (.git, package.json, pom.xml, ...).'
}

$exactDocs = @($repos | Where-Object { $_.ToLowerInvariant() -eq 'docs' })
if ($DocsRepo -and ($repos -notcontains $DocsRepo)) {
  Fail 'docs-repo-missing' "No code root named $DocsRepo"
}

$projectFile = Join-Path $Workspace 'project.yaml'
$localFile = Join-Path $Workspace 'project.local.yaml'
$kept = New-Object System.Collections.Generic.List[string]
$docsPath = 'docs'

if (Test-Path -LiteralPath $projectFile) {
  $existingProject = Read-SimpleYaml $projectFile
  $existingMode = ''
  $existingPath = ''
  if ($existingProject.docs) {
    $existingMode = [string]$existingProject.docs.mode
    $existingPath = [string]$existingProject.docs.path
  }
  if ($PSBoundParameters.ContainsKey('DocsMode') -and $existingMode -and $DocsMode -ne $existingMode) {
    Fail 'docs-mode-conflict' "project.yaml docs.mode is $existingMode. Edit that file; install does not change it."
  }
  if ($PSBoundParameters.ContainsKey('DocsRepo') -and $existingPath -and $DocsRepo -ne $existingPath) {
    Fail 'docs-repo-conflict' "project.yaml docs.path is $existingPath. Edit that file; install does not change it."
  }
  if ($existingMode) { $DocsMode = $existingMode }
  if ($existingPath) { $docsPath = $existingPath }
  $kept.Add('project.yaml')
}
else {
  if (-not $DocsMode) {
    if ($DocsRepo) { $DocsMode = 'repo' }
    elseif ($exactDocs.Count -eq 1) { $DocsMode = 'repo' }
    elseif ($SharePath) { $DocsMode = 'share' }
    else { $DocsMode = 'local' }
  }
  if ($DocsMode -notin @('local', 'share', 'repo')) { Fail 'docs-mode' $DocsMode }
  if ($DocsMode -eq 'share' -and -not $SharePath) { Fail 'share-path-required' 'Pass -SharePath for docs mode share.' }
  if ($DocsMode -eq 'local' -and $exactDocs.Count -eq 1) {
    Fail 'docs-repo-present' 'A code repository named docs is the docs library. Re-run with -DocsMode repo, or rename that folder.'
  }
  if ($DocsMode -eq 'repo') {
    if ($DocsRepo) { $docsPath = $DocsRepo }
    elseif ($exactDocs.Count -eq 1) { $docsPath = $exactDocs[0] }
    else { Fail 'docs-repo-missing' 'Name the docs git repo docs, or pass -DocsRepo <folder>.' }
  }
  $appRepos = @($repos)
  if ($DocsMode -eq 'repo') { $appRepos = @($repos | Where-Object { $_ -ne $docsPath }) }
  $repoLines = ($appRepos | ForEach-Object { "  ${_}: ${_}" }) -join "`n"
  $yaml = @"
# Generated by dev-ai-kit. Machine paths belong in project.local.yaml.

project: $(Split-Path -Leaf $Workspace)

repos:
$repoLines

docs:
  mode: $DocsMode
  path: $docsPath

runtime:
  backend:
    start: ""
  frontend:
    start: ""
  database:
    readonly: false
    bitwarden: ""
  test: ""
"@
  Write-Utf8 $projectFile $yaml
  Write-Output 'WROTE project.yaml'
}

if (-not (Test-Path -LiteralPath $localFile)) {
  $shareValue = ''
  if ($SharePath) { $shareValue = ($SharePath -replace '\\', '/') }
  $localYaml = @"
# Local only. Do not commit.

kit:
  path: $($Kit -replace '\\', '/')

share:
  path: "$shareValue"

current: ""
"@
  Write-Utf8 $localFile $localYaml
  Write-Output 'WROTE project.local.yaml'
}
else { $kept.Add('project.local.yaml') }

$ruleSrc = Join-Path $Kit 'rules\dev-ai-kit.mdc'
$ruleDst = Join-Path $Workspace '.cursor\rules\dev-ai-kit.mdc'
if (-not (Test-Path -LiteralPath $ruleDst)) {
  New-Item -ItemType Directory -Force -Path (Split-Path -Parent $ruleDst) | Out-Null
  Copy-Item -LiteralPath $ruleSrc -Destination $ruleDst
  Write-Output 'WROTE .cursor/rules/dev-ai-kit.mdc'
}
else {
  $same = (Get-FileHash -LiteralPath $ruleSrc).Hash -eq (Get-FileHash -LiteralPath $ruleDst).Hash
  if ($same) { $kept.Add('rule') }
  else {
    $kept.Add('rule-differs')
    Write-Output 'KEPT .cursor/rules/dev-ai-kit.mdc differs from kit; not overwritten'
  }
}

$project = Read-SimpleYaml $projectFile
$local = Read-SimpleYaml $localFile
$docsRoot = Resolve-DocsRoot $Workspace $project $local
if (-not $docsRoot) { Fail 'docs-root' 'Could not resolve docs path from yaml' }
New-Item -ItemType Directory -Force -Path $docsRoot | Out-Null
$readme = Join-Path $docsRoot 'README.md'
if (-not (Test-Path -LiteralPath $readme)) {
  Copy-Item -LiteralPath (Join-Path $Kit 'templates\docs-readme.md') -Destination $readme
  Write-Output 'WROTE docs/README.md'
}
$teamSrc = Join-Path $Kit 'templates\team'
$teamDst = Join-Path $docsRoot 'team'
New-Item -ItemType Directory -Force -Path $teamDst | Out-Null
Get-ChildItem -LiteralPath $teamSrc -File | ForEach-Object {
  $dest = Join-Path $teamDst $_.Name
  if (-not (Test-Path -LiteralPath $dest)) {
    Copy-Item -LiteralPath $_.FullName -Destination $dest
    Write-Output "WROTE team/$($_.Name)"
  }
}

if ($DocsMode -eq 'share' -or ($local.share -and [string]$local.share.path)) {
  $share = $SharePath
  if (-not $share -and $local.share) { $share = [string]$local.share.path }
  if ($share) {
    $index = Join-Path $share 'index.md'
    if (-not (Test-Path -LiteralPath $index)) {
      New-Item -ItemType Directory -Force -Path $share | Out-Null
      Copy-Item -LiteralPath (Join-Path $Kit 'templates\share\index.md') -Destination $index
      Write-Output 'WROTE share/index.md'
    }
  }
}

$ignore = Join-Path $Workspace '.gitignore'
$lines = @('project.local.yaml', 'skill.md')
if ($DocsMode -eq 'local') { $lines += '/docs/' }
$existing = ''
if (Test-Path -LiteralPath $ignore) { $existing = [System.IO.File]::ReadAllText($ignore) }
$added = @()
foreach ($line in $lines) {
  if ($existing -notmatch [regex]::Escape($line)) { $added += $line }
}
if ($added.Count -gt 0) {
  $block = "`r`n# dev-ai-kit`r`n" + ($added -join "`r`n") + "`r`n"
  if (-not (Test-Path -LiteralPath $ignore)) { Write-Utf8 $ignore ($block.TrimStart()) }
  else { [System.IO.File]::AppendAllText($ignore, $block) }
  Write-Output 'WROTE .gitignore entries'
}

& powershell.exe -NoProfile -File (Join-Path $PSScriptRoot 'validate.ps1') -Workspace $Workspace
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
if ($kept.Count -gt 0) { Write-Output ("KEPT " + ($kept -join ',')) }
Write-Output 'OK install'
exit 0
